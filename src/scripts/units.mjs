// نمط «رقم + وحدة» المشترك بين مكوّنات الصفحة وإضافة rehype التي تعالج نص الدروس.
const UNITS = [
  '°C', 'K', 'kg·m/s', 'kg', 'g', 'm/s²', 'm/s', 'km/h', 'km/s', 'km', 'cm', 'mm', 'm³', 'm',
  'N/m', 'N·m²/kg²', 'N·m', 'N', 'J/K', 'J/\\(kg·°C\\)', 'J/\\(mol·K\\)', 'J', 'kPa', 'Pa', 'L', 'AU', 'rad/s', 'Hz', 'mol', 's', 'y', 'W',
  'µK', 'nK', 'pK',
];
const SCI = String.raw`\s?×\s?10(?:\^?[−-]?\d+|[⁰¹²³⁴-⁹⁻]+)`;
const NUM = String.raw`[−-]?\d+(?:[.,]\d+)*`;

/**
 * رقم (قد يكون سالبًا أو بصيغة علمية) تتبعه وحدة ولا يليه حرف لاتيني،
 * أو رقم بصيغة علمية وحده، أو رقم سالب وحده.
 */
export const UNIT_SOURCE =
  `${NUM}(?:${SCI})?\\s?(?:${UNITS.join('|')})(?![A-Za-z])` + `|${NUM}${SCI}` + `|[−-]\\d+(?:[.,]\\d+)*`;
